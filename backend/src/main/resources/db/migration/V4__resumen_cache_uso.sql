-- Migración de caché de resúmenes y control de coste (FT00021).
--
-- Añade dos tablas **propias y separadas** de `resumen` (que guarda el resumen
-- publicado):
--
--   * `resumen_cache`: el `ResumenDto` serializado por clave determinista
--     (publicación + modelo + versión del prompt). Es un *upsert* idempotente por
--     `cache_key`; un cambio de modelo o de versión del prompt produce una clave
--     distinta y no sirve un resumen obsoleto.
--   * `generacion_uso`: un **log** de consumo de tokens por generación (acierto de
--     caché o llamada al proveedor). **Sin** FK a `publicacion`: es un registro de
--     coste que no debe impedir borrar una publicación. Registra tokens, no
--     tarifas (la conversión monetaria, si llega, es de operación).
--
-- V1/V2/V3 no se editan (regla de migraciones Flyway). La migración queda **fuera**
-- de `build`/`check` (se aplica con `./gradlew :backend:flywayMigrate`).

CREATE TABLE resumen_cache (
    cache_key      text PRIMARY KEY,
    publicacion_id text NOT NULL REFERENCES publicacion (id) ON DELETE CASCADE,
    modelo         text NOT NULL,
    prompt_version text NOT NULL,
    resumen        text NOT NULL,
    creado_en      timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX resumen_cache_publicacion_id_idx ON resumen_cache (publicacion_id);

CREATE TABLE generacion_uso (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    publicacion_id    text NOT NULL,
    cache_key         text NOT NULL,
    modelo            text NOT NULL,
    prompt_tokens     integer NOT NULL DEFAULT 0,
    completion_tokens integer NOT NULL DEFAULT 0,
    total_tokens      integer NOT NULL DEFAULT 0,
    cache_hit         boolean NOT NULL DEFAULT false,
    creado_en         timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX generacion_uso_publicacion_id_idx ON generacion_uso (publicacion_id);
